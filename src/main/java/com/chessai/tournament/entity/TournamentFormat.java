package com.chessai.tournament.entity;

/**
 * Формат турнира
 */
public enum TournamentFormat {
    /**
     * Круговой турнир (все со всеми)
     */
    ROUND_ROBIN,
    
    /**
     * Швейцарская система
     */
    SWISS,
    
    /**
     * Олимпийская система (плей-офф)
     */
    KNOCKOUT,
    
    /**
     * Двухкруговой турнир
     */
    DOUBLE_ROUND_ROBIN
}






