package com.chessai.tournament.entity;

/**
 * Роли пользователей в системе турниров
 */
public enum Role {
    
    /**
     * Обычный пользователь - может просматривать турниры и регистрироваться
     */
    USER,
    
    /**
     * Организатор турниров - может создавать и управлять турнирами
     */
    ORGANIZER,
    
    /**
     * Администратор - полный доступ ко всем функциям
     */
    ADMIN
}



